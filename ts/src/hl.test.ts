// Both files are generated by the Go side, which checks itself against them. The order vectors are Hyperliquid's own bytes for
// an order action, which every held order is built from: this test reads the actions alone.
interface OrderVector {
  name: string
  cloid: string
  asset: number
  px: string
  sz: string
  expiresAfter: number
  action: unknown
  msgpackHex: string
  nonce: number
  actionHash: string
  source: string
  digest: string
  signature: { r: string; s: string; v: number }
  agent: string
  body: { action: unknown; nonce: number; signature: { r: string; s: string; v: number }; expiresAfter: number }
}
interface OrderVectors {
  agentKey: string
  domain: { name: string; version: string; chainId: number; verifyingContract: string }
  types: { Agent: { name: string; type: string }[] }
  orders: OrderVector[]
}
interface Hip4Vectors {
  canonical: { in: string; want: string }[]
  refused: string[]
  prices: { milli: number; ticks: number; px: string; complement: string }[]
  ids: { outcome: number; side: number; asset: number; coin: string; token: string }[]
  minValueOk: [string, string][]
  minValueNo: [string, string][]
  offTick: string[]
  badSizes: string[]
  constants: Record<string, number>
}

const read = <T>(name: string): T => JSON.parse(readFileSync(new URL(`../../testdata/${name}`, import.meta.url), "utf8")) as T
const vectors = read<OrderVectors>("hl_order_vectors.json")
const hip4 = read<Hip4Vectors>("hip4_vectors.json")

// The vectors' agent key is a PUBLIC anvil dev key (#2); it is read from the file, never written here.
const agent = privateKeyToAccount(vectors.agentKey as Hex)

describe("the vectors", () => {
  it("are the files this test was written against", () => {
    // Four actions, signed for both of Hyperliquid's networks ("a" mainnet, "b" testnet).
    assert.deepEqual(
      vectors.orders.map((v) => v.source),
      ["b", "b", "a", "b"],
    )
    assert.deepEqual(vectors.domain, L1_DOMAIN)
    assert.deepEqual(vectors.types, AGENT_TYPES)
    assert.equal(agent.address.toLowerCase(), vectors.orders[0]?.agent)
  })
})

describe("an order action, byte for byte (testdata/hl_order_vectors.json)", () => {
  for (const v of vectors.orders) {
    describe(v.name, () => {
      const mainnet = v.source === "a"
      const action = orderAction({ asset: v.asset, isBuy: true, px: v.px, sz: v.sz, tif: "Ioc", cloid: v.cloid as Hex })

      it("the asset, and the action and its JSON in the hashed key order", () => {
        const id = fromAsset(v.asset)
        assert.ok(id !== undefined)
        assert.equal(asset(id.outcome, id.side), v.asset)
        assert.equal(pxString(parsePx(v.px)), v.px)
        assert.deepEqual(action, v.action)
        assert.equal(actionJson(action), JSON.stringify(v.action), "the hashed key order is the JSON's")
      })

      it("the msgpack, the action hash and the phantom agent's digest", () => {
        assert.equal(Buffer.from(msgpack(action as unknown as MsgValue)).toString("hex"), v.msgpackHex)
        assert.equal(actionHash(action as unknown as MsgValue, v.nonce, v.expiresAfter), v.actionHash)
        const td = phantomAgentTypedData(v.actionHash as Hex, mainnet)
        assert.equal(td.message.source, v.source)
        assert.equal(l1Digest(v.actionHash as Hex, mainnet), v.digest)
        assert.equal(hashTypedData(td), v.digest, "viem hashes the same typed data")
      })

      it("the signature: viem's, the vector's, it recovers to the agent, and the exchange body", async () => {
        const td = phantomAgentTypedData(v.actionHash as Hex, mainnet)
        const sig = await agent.signTypedData(td)
        assert.deepEqual(splitSignature(sig), v.signature)
        assert.equal((await recoverTypedDataAddress({ ...td, signature: sig })).toLowerCase(), v.agent)
        assert.deepEqual({ action, nonce: v.nonce, signature: splitSignature(sig), expiresAfter: v.expiresAfter }, v.body)
      })
    })
  }

  it("refuses a non-canonical px or sz: \"0.90\" and \"0.9\" are two actions to Hyperliquid", () => {
    const v = vectors.orders[0]!
    assert.throws(() => orderAction({ asset: v.asset, isBuy: true, px: "0.4520", sz: v.sz, tif: "Ioc" }), (e: unknown) => e instanceof HlRuleError && e.rule === "number")
    assert.throws(() => orderAction({ asset: v.asset, isBuy: true, px: v.px, sz: "100.0", tif: "Ioc" }), (e: unknown) => e instanceof HlRuleError && e.rule === "number")
    assert.throws(() => orderAction({ asset: v.asset, isBuy: true, px: "0.90", sz: "10", tif: "Ioc" }), HlRuleError)
  })
})

describe("the HIP-4 rules (testdata/hip4_vectors.json)", () => {
  it("the constants", () => {
    const c = hip4.constants
    const hl = {
      assetBase: c.assetBase,
      tokenBase: c.tokenBase,
      pxDecimals: c.pxDecimals,
      ticks: c.ticks,
      szDecimals: c.szDecimals,
      minOrderValueMicro: c.minOrderValueMicro,
      tokenWeiPerShare: c.tokenWeiPerShare,
    }
    assert.deepEqual(hl, {
      assetBase: ASSET_BASE,
      tokenBase: TOKEN_BASE,
      pxDecimals: PX_DECIMALS,
      ticks: TICKS,
      szDecimals: SZ_DECIMALS,
      minOrderValueMicro: Number(MIN_ORDER_VALUE_MICRO),
      tokenWeiPerShare: Number(TOKEN_WEI_PER_SHARE),
    })
  })

  it("canonical strings, and the numbers it refuses", () => {
    for (const c of hip4.canonical) {
      assert.equal(canonical(c.in), c.want, c.in)
      assert.ok(isCanonical(c.want), c.want)
    }
    for (const r of hip4.refused) {
      assert.throws(() => canonical(r), (e: unknown) => e instanceof HlRuleError && e.rule === "number", JSON.stringify(r))
      assert.equal(isCanonical(r), false)
    }
  })

  it("prices: milli to ticks, the canonical string and the complement", () => {
    for (const p of hip4.prices) {
      assert.equal(pxFromMilli(p.milli), p.ticks)
      assert.equal(pxString(p.ticks), p.px)
      assert.equal(pxString(complement(p.ticks)), p.complement)
      assert.equal(parsePx(p.px), p.ticks)
    }
    for (const s of hip4.offTick) assert.throws(() => parsePx(s), (e: unknown) => e instanceof HlRuleError && e.rule === "tick", s)
    for (const s of ["0", "1", "1.5"]) assert.throws(() => parsePx(s), (e: unknown) => e instanceof HlRuleError && e.rule === "price", s)
  })

  it("sizes are whole shares", () => {
    for (const s of hip4.badSizes) assert.throws(() => parseSz(s), (e: unknown) => e instanceof HlRuleError && e.rule === "size", s)
    assert.equal(parseSz("12"), 12n)
  })

  it("ids: asset, book coin, balance token", () => {
    for (const id of hip4.ids) {
      const side = id.side as Side
      assert.equal(asset(id.outcome, side), id.asset)
      assert.equal(coin(id.outcome, side), id.coin)
      assert.equal(token(id.outcome, side), id.token)
      assert.deepEqual(fromAsset(id.asset), { outcome: id.outcome, side })
    }
    assert.equal(fromAsset(ASSET_BASE + 2), undefined, "side 2 is no outcome side")
    assert.equal(fromAsset(7), undefined)
  })

  it("Hyperliquid's 1 USDC minimum on an order's own value", () => {
    for (const [sz, px] of hip4.minValueOk) assert.doesNotThrow(() => checkValue(parseSz(sz), parsePx(px)), `${sz} at ${px}`)
    for (const [sz, px] of hip4.minValueNo) {
      assert.throws(() => checkValue(parseSz(sz), parsePx(px)), (e: unknown) => e instanceof HlRuleError && e.rule === "user_value", `${sz} at ${px}`)
    }
  })

  it("the sides", () => {
    assert.equal(YES, 0)
    assert.equal(NO, 1)
  })
})

describe("the msgpack subset", () => {
  it("writes the shortest integer and string headers", () => {
    const hex = (v: Parameters<typeof msgpack>[0]) => Buffer.from(msgpack(v)).toString("hex")
    assert.equal(hex(0), "00")
    assert.equal(hex(127), "7f")
    assert.equal(hex(128), "cc80")
    assert.equal(hex(256), "cd0100")
    assert.equal(hex(65536), "ce00010000")
    assert.equal(hex(2 ** 32), "cf0000000100000000")
    assert.equal(hex(1760000000000n), "cf00000199c82cc000")
    assert.equal(hex("a".repeat(31)).slice(0, 2), "bf")
    assert.equal(hex("a".repeat(32)).slice(0, 4), "d920")
    assert.equal(hex(null), "c0")
    assert.equal(hex([true, false]), "92c3c2")
    assert.equal(hex({ b: 1, a: 2 }), "82a16201a16102", "keys in insertion order, not sorted")
  })

  it("refuses a float and a negative number: amounts are decimal strings", () => {
    assert.throws(() => msgpack(0.5), RangeError)
    assert.throws(() => msgpack(-1), RangeError)
    assert.throws(() => msgpack(1n << 64n), RangeError)
  })
})

describe("viem compatibility (type level)", () => {
  it("phantomAgentTypedData is what signTypedData takes", () => {
    // This assignment is the test: it fails to COMPILE (make ts-test runs tsc over this file) if
    // the payload stops being a valid viem TypedDataDefinition.
    const td: TypedDataDefinition<typeof AGENT_TYPES, "Agent"> = phantomAgentTypedData(vectors.orders[0]!.actionHash as Hex, false)
    assert.equal(td.primaryType, "Agent")
  })

  it("splitSignature writes r and s as minimal hex and v as 27 or 28", () => {
    const sig = `0x${"00".repeat(31)}01${"00".repeat(31)}02${"01"}` as Hex
    assert.deepEqual(splitSignature(sig), { r: "0x1", s: "0x2", v: 28 })
    assert.throws(() => splitSignature("0x12" as Hex), TypeError)
  })

  it("splitSignature sends a high s as its low twin, v flipped (EIP-2), as the edge stores it", () => {
    const n = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n
    const high = (n - 2n).toString(16).padStart(64, "0")
    assert.deepEqual(splitSignature(`0x${"00".repeat(31)}01${high}1b` as Hex), { r: "0x1", s: "0x2", v: 28 })
    assert.deepEqual(splitSignature(`0x${"00".repeat(31)}01${high}1c` as Hex), { r: "0x1", s: "0x2", v: 27 })
    // The signer's own: a vector's signature is already canonical and stays as it is.
    const v = vectors.orders[0]!
    const given = v.signature as { r: string; s: string; v: number }
    const raw = `0x${BigInt(given.r).toString(16).padStart(64, "0")}${BigInt(given.s).toString(16).padStart(64, "0")}${given.v.toString(16)}` as Hex
    assert.deepEqual(splitSignature(raw), given)
    assert.throws(() => splitSignature(`0x${"00".repeat(64)}1b` as Hex), TypeError)
  })
})
