/**
 * testdata/held_vectors.json is generated by the Go side: a
 * maker's held orders with every byte that is hashed, the signatures, the API's JSON and the
 * request bodies the pool relays. This client must reproduce all of it.
 */
interface SignedVector {
  action: unknown
  msgpackHex: string
  nonce: number
  expiresAfter: number
  actionHash: string
  digest: string
  signature: { r: string; s: string; v: number }
  body: string
}
interface HeldVector {
  name: string
  mainnet: boolean
  source: string
  account: string
  signer: string
  book: number
  side: number
  isBuy: boolean
  px: string
  sz: string
  tif: string
  cloid: string
  asset: number
  place: SignedVector
  clear: SignedVector
  orderId: string
  heldOrder: HeldOrderWire
}
interface HeldVectors {
  signerKey: string
  orders: HeldVector[]
  bookUpdate: { seq: string; strict: boolean; orders: HeldOrderWire[] }
}

const vectors = JSON.parse(readFileSync(new URL("../../testdata/held_vectors.json", import.meta.url), "utf8")) as HeldVectors
// The vectors' key is a PUBLIC anvil dev key; it is read from the file, never written here.
const wallet = privateKeyToAccount(vectors.signerKey as Hex)
const toHex = (b: Uint8Array): string => `0x${Buffer.from(b).toString("hex")}`
// The file leads with the mainnet case (source "a"); the cases of source "b" are one book's, and the
// first two of them are the book update.
const sourceB = vectors.orders.filter((o) => o.source === "b")

const draftOf = (v: HeldVector): HeldDraft => ({
  account: v.account as Hex,
  signer: v.signer as Hex,
  book: v.book,
  side: v.side as Side,
  isBuy: v.isBuy,
  px: v.px,
  sz: v.sz,
  cloid: v.cloid as Hex,
  nonce: v.place.nonce,
  clearNonce: v.clear.nonce,
  expiresAfter: v.place.expiresAfter,
  clearExpiresAfter: v.clear.expiresAfter,
  mainnet: v.mainnet,
})

describe("held orders against the Go vectors (testdata/held_vectors.json)", () => {
  assert.ok(vectors.orders.length >= 4)

  for (const v of vectors.orders) {
    it(`${v.name}: the two actions, their msgpack, hashes and digests`, () => {
      const d = draftOf(v)
      const place = heldPlaceAction(d)
      const clear = heldClearAction(v.asset, v.cloid as Hex)
      // The JSON in the hashed key order, byte for byte.
      assert.equal(JSON.stringify(place), JSON.stringify(v.place.action))
      assert.equal(JSON.stringify(clear), JSON.stringify(v.clear.action))
      assert.equal(place.orders[0]?.a, v.asset)
      assert.equal(place.orders[0]?.t.limit.tif, "Alo")
      assert.equal(toHex(msgpack(place as unknown as MsgValue)), v.place.msgpackHex)
      assert.equal(toHex(msgpack(clear as unknown as MsgValue)), v.clear.msgpackHex)
      const placeHash = actionHash(place as unknown as MsgValue, v.place.nonce, v.place.expiresAfter)
      const clearHash = actionHash(clear as unknown as MsgValue, v.clear.nonce, v.clear.expiresAfter)
      assert.equal(placeHash, v.place.actionHash)
      assert.equal(clearHash, v.clear.actionHash)
      assert.equal(l1Digest(placeHash, v.mainnet), v.place.digest)
      assert.equal(l1Digest(clearHash, v.mainnet), v.clear.digest)
      assert.equal(phantomAgentTypedData(placeHash, v.mainnet).message.source, v.source)
    })

    it(`${v.name}: signed with the key, it is the API's JSON and the bodies the pool relays`, async () => {
      const signed = await signHeldOrder(draftOf(v), (p) => wallet.signTypedData(p))
      assert.deepEqual(signed, v.heldOrder)
      // Key for key too: the JSON a maker sends is exactly the vector's.
      assert.equal(JSON.stringify(signed), JSON.stringify(v.heldOrder))
      assert.deepEqual(signed.place.signature, v.place.signature)
      assert.deepEqual(signed.clear.signature, v.clear.signature)
      assert.equal(signed.signer, wallet.address.toLowerCase())
      // Each half is Hyperliquid's own request body: what the pool stores and relays.
      assert.equal(JSON.stringify(signed.place), v.place.body)
      assert.equal(JSON.stringify(signed.clear), v.clear.body)
      // And the signatures recover to the signer under Hyperliquid's L1 domain.
      for (const [half, vec] of [
        [signed.place, v.place],
        [signed.clear, v.clear],
      ] as const) {
        const sig = half.signature
        const raw = `0x${sig.r.slice(2).padStart(64, "0")}${sig.s.slice(2).padStart(64, "0")}${sig.v.toString(16)}` as Hex
        const who = await recoverTypedDataAddress({ ...phantomAgentTypedData(vec.actionHash as Hex, v.mainnet), signature: raw })
        assert.equal(who.toLowerCase(), v.signer)
      }
    })
  }

  it("a book update is the orders under a seq", async () => {
    const orders = await Promise.all(sourceB.slice(0, 2).map((v) => signHeldOrder(draftOf(v), (p) => wallet.signTypedData(p))))
    assert.equal(JSON.stringify({ seq: vectors.bookUpdate.seq, strict: false, orders }), JSON.stringify(vectors.bookUpdate))
  })

  it("the signer defaults to the account", async () => {
    const v = vectors.orders.find((o) => o.account === o.signer)
    assert.ok(v, "a vector signed by the account's own key")
    const { signer: _omitted, ...draft } = draftOf(v)
    const signed = await signHeldOrder(draft, (p) => wallet.signTypedData(p))
    assert.equal(signed.signer, v.account)
    assert.deepEqual(signed, v.heldOrder)
  })
})

describe("held orders: what the builders refuse", () => {
  const good = draftOf(sourceB[0] as HeldVector)

  it("a number that is not canonical, a price off the tick, a fraction of a share, a value under 1 USDC", () => {
    assert.throws(() => heldPlaceAction({ ...good, px: "0.550" }), HlRuleError)
    assert.throws(() => heldPlaceAction({ ...good, px: ".55" }), HlRuleError)
    assert.throws(() => heldPlaceAction({ ...good, px: "0.512345" }), HlRuleError)
    assert.throws(() => heldPlaceAction({ ...good, px: "1" }), HlRuleError)
    assert.throws(() => heldPlaceAction({ ...good, sz: "2.5" }), HlRuleError)
    assert.throws(() => heldPlaceAction({ ...good, sz: "0" }), RangeError)
    assert.throws(() => heldPlaceAction({ ...good, sz: "1" }), HlRuleError) // 1 x 0.55 is under 1 USDC
    assert.doesNotThrow(() => heldPlaceAction({ ...good, px: "0.5", sz: "2" })) // exactly 1 USDC passes
  })

  it("a cloid that is missing, short or zero", () => {
    assert.throws(() => heldPlaceAction({ ...good, cloid: "0x1234" as Hex }), TypeError)
    assert.throws(() => heldPlaceAction({ ...good, cloid: `0x${"0".repeat(32)}` as Hex }), TypeError)
    assert.throws(() => heldClearAction(100_042_420, "0xabc" as Hex), TypeError)
    assert.throws(() => heldClearAction(3, good.cloid), TypeError)
    const c = randomCloid()
    assert.match(c, /^0x[0-9a-f]{32}$/u)
    assert.notEqual(c, randomCloid())
  })

  it("a clear for another order, one nonce for both, a time in force that is not Alo", async () => {
    const v = sourceB[0] as HeldVector
    const signed = await signHeldOrder(good, (p) => wallet.signTypedData(p))
    const sig = `0x${"11".repeat(64)}1b` as Hex
    const place = { action: signed.place.action, nonce: v.place.nonce, expiresAfter: v.place.expiresAfter, signature: sig }
    const clear = { action: signed.clear.action, nonce: v.clear.nonce, expiresAfter: v.clear.expiresAfter, signature: sig }
    assert.doesNotThrow(() => heldOrder({ account: good.account, place, clear }))
    assert.throws(() => heldOrder({ account: good.account, place, clear: { ...clear, nonce: v.place.nonce } }), RangeError)
    assert.throws(
      () => heldOrder({ account: good.account, place, clear: { ...clear, action: heldClearAction(100_042_421, good.cloid) } }),
      /own asset and cloid/u,
    )
    const ioc = { ...signed.place.action, orders: [{ ...signed.place.action.orders[0]!, t: { limit: { tif: "Ioc" } } }] }
    assert.throws(() => heldOrder({ account: good.account, place: { ...place, action: ioc }, clear }), /post-only/u)
    assert.throws(() => heldOrder({ account: "0x12" as Hex, place, clear }), TypeError)
    await assert.rejects(signHeldOrder({ ...good, clearNonce: good.nonce }, (p) => wallet.signTypedData(p)), RangeError)
  })
})

describe("the held REST client", () => {
  interface Seen {
    method: string
    url: string
    key: string | null
    body: unknown
  }
  const serve = (answers: (seen: Seen, n: number) => Response, extra: { maxAttempts?: number; withdrawAttempts?: number } = {}) => {
    const calls: Seen[] = []
    const sleeps: number[] = []
    let keys = 0
    const fake: typeof fetch = async (input, init) => {
      const headers = new Headers(init?.headers)
      const seen: Seen = {
        method: init?.method ?? "GET",
        url: String(input),
        key: headers.get(MAKER_KEY_HEADER),
        body: typeof init?.body === "string" ? JSON.parse(init.body) : undefined,
      }
      calls.push(seen)
      return answers(seen, calls.length)
    }
    const client = createMakerClient({
      baseUrl: "https://api.example/",
      makerKey: () => {
        keys += 1
        return "skm_test"
      },
      fetch: fake,
      sleep: async (ms) => void sleeps.push(ms),
      ...extra,
    })
    return { calls, sleeps, client, keys: () => keys }
  }
  const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } })

  it("sends each call to its path with the maker's key", async () => {
    const { calls, client } = serve(() => json({ applied: true }))
    const order = sourceB[0]!.heldOrder
    await client.getBookRules(4242)
    await client.replaceBookOrders(4242, { seq: 1793966400000n, orders: [order] })
    await client.withdrawBook(4242)
    await client.withdrawBook(4242, 9)
    await client.withdrawAll()
    await client.listOrders({ book: 4242, states: ["HELD_ORDER_STATE_LIVE", "HELD_ORDER_STATE_EXPIRED"], limit: 10 })
    await client.getOrder("0x874c1039678708dfbffdc548dc9ad276")
    assert.deepEqual(
      calls.map((c) => `${c.method} ${c.url}`),
      [
        "GET https://api.example/api/v1/held/books/4242/rules",
        "POST https://api.example/api/v1/held/books/4242/orders",
        "POST https://api.example/api/v1/held/withdraw",
        "POST https://api.example/api/v1/held/withdraw",
        "POST https://api.example/api/v1/held/withdraw",
        "GET https://api.example/api/v1/held/orders?book=4242&states=HELD_ORDER_STATE_LIVE&states=HELD_ORDER_STATE_EXPIRED&limit=10",
        "GET https://api.example/api/v1/held/orders/0x874c1039678708dfbffdc548dc9ad276",
      ],
    )
    assert.ok(calls.every((c) => c.key === "skm_test"))
    assert.deepEqual(calls[1]?.body, { seq: "1793966400000", strict: false, orders: [order] })
    assert.deepEqual(calls[2]?.body, { book: 4242 })
    assert.deepEqual(calls[3]?.body, { book: 4242, seq: "9" })
    assert.deepEqual(calls[4]?.body, { allBooks: true })
  })

  it("turns an error into RfqApiError with the edge's code and retry hint", async () => {
    const detail = { "@type": "type.googleapis.com/rfq.v1.ErrorDetail", reason: "RATE_LIMITED", retryAfterMs: 250 }
    const { client } = serve(() => json({ code: "RATE_LIMITED", message: "too many requests (held-book); retry shortly", details: [detail] }, 429))
    await assert.rejects(client.withdrawBook(1), (e: unknown) => {
      assert.ok(e instanceof RfqApiError)
      assert.equal(e.status, 429)
      assert.equal(e.code, "RATE_LIMITED")
      assert.equal(e.retryAfterMs, 250)
      assert.ok(e.retryable)
      return true
    })
    const { client: denied } = serve(() => json({ code: "UNAUTHENTICATED", message: "authentication required" }, 401))
    await assert.rejects(denied.getBookRules(1), (e: unknown) => e instanceof RfqApiError && e.code === "UNAUTHENTICATED" && !e.retryable)
  })

  it("reads the feed line by line, across chunk boundaries, heartbeats included", async () => {
    const lines = [
      `{"result":{"cursor":"3","type":"heartbeat"}}\n`,
      `{"result":{"cursor":"4","type":"replaced","book":4242,"seq":"2","orders":[{"orderId":"0xaa","cloid":"0xbb","state":"HELD_ORDER_STATE_REPLACED"}]}}\n{"result":{"cur`,
      `sor":"5","type":"accepted","book":4242,"seq":"2"}}\n`,
    ]
    const { calls, client } = serve(
      () =>
        new Response(
          new ReadableStream<Uint8Array>({
            start(c) {
              for (const l of lines) c.enqueue(new TextEncoder().encode(l))
              c.close()
            },
          }),
          { status: 200 },
        ),
    )
    const got: string[] = []
    for await (const ev of client.watchOrders({ cursor: 3, epoch: "0123456789abcdef", book: 4242, reconnect: false })) got.push(`${ev.cursor}:${ev.type}`)
    assert.deepEqual(got, ["3:heartbeat", "4:replaced", "5:accepted"])
    assert.equal(calls[0]?.url, "https://api.example/api/v1/held/events?cursor=3&epoch=0123456789abcdef&book=4242")
    // From now on: no cursor is sent.
    for await (const _ of client.watchOrders({ reconnect: false })) void _
    assert.equal(calls[1]?.url, "https://api.example/api/v1/held/events")
  })

  it("a stream refused at its opening carries the stream's error shape", async () => {
    const detail = { "@type": "type.googleapis.com/rfq.v1.ErrorDetail", reason: "TOO_MANY_STREAMS" }
    const { client } = serve(() => json({ error: { code: 8, message: "[TOO_MANY_STREAMS] too many concurrent streams", details: [detail] } }, 429))
    await assert.rejects(
      (async () => {
        for await (const _ of client.watchOrders({ cursor: 2, epoch: "0123456789abcdef", reconnect: false })) void _
      })(),
      (e: unknown) => e instanceof RfqApiError && e.status === 429 && e.code === "TOO_MANY_STREAMS",
    )
  })

  it("the position to reconnect from keeps a cursor with its epoch, and a reset moves both", () => {
    let at = advanceHeldFeed(undefined, { type: "heartbeat", epoch: "e1" })
    assert.deepEqual(at, { cursor: "0", epoch: "e1" })
    at = advanceHeldFeed(at, { type: "accepted", cursor: "1", book: 4242 })
    at = advanceHeldFeed(at, { type: "replaced", cursor: "2", book: 4242 })
    assert.deepEqual(at, { cursor: "2", epoch: "e1" })
    at = advanceHeldFeed(at, { type: "heartbeat", cursor: "2", epoch: "e1" })
    assert.deepEqual(at, { cursor: "2", epoch: "e1" })
    // The pool restarted: the next run counts from 0, under its own epoch.
    at = advanceHeldFeed(at, { type: "reset", epoch: "e2", resetReason: HELD_RESET_POOL_EMPTY })
    assert.deepEqual(at, { cursor: "0", epoch: "e2" })
    // Events missed: the same run, further on.
    at = advanceHeldFeed({ cursor: "3", epoch: "e2" }, { type: "reset", cursor: "90", epoch: "e2", resetReason: HELD_RESET_EVENTS_MISSED })
    assert.deepEqual(at, { cursor: "90", epoch: "e2" })
    // Nothing to stand on before the stream's first heartbeat.
    assert.equal(advanceHeldFeed(undefined, { type: "accepted", cursor: "1" }), undefined)
    // A position only moves forward in an epoch: a heartbeat at or under it, or with no cursor, leaves it.
    assert.deepEqual(advanceHeldFeed({ cursor: "7", epoch: "e2" }, { type: "heartbeat", epoch: "e2" }), { cursor: "7", epoch: "e2" })
    assert.deepEqual(advanceHeldFeed({ cursor: "7", epoch: "e2" }, { type: "heartbeat", cursor: "3", epoch: "e2" }), { cursor: "7", epoch: "e2" })
    assert.deepEqual(advanceHeldFeed({ cursor: "7", epoch: "e2" }, { type: "heartbeat", cursor: "9", epoch: "e2" }), { cursor: "9", epoch: "e2" })
    // Under another epoch it starts over; a reset goes where the reset says, even back.
    assert.deepEqual(advanceHeldFeed({ cursor: "7", epoch: "e2" }, { type: "heartbeat", epoch: "e3" }), { cursor: "0", epoch: "e3" })
    assert.deepEqual(advanceHeldFeed({ cursor: "7", epoch: "e2" }, { type: "reset", cursor: "3", epoch: "e2", resetReason: HELD_RESET_EVENTS_MISSED }), { cursor: "3", epoch: "e2" })
  })

  it("a reconnect sends the epoch even at cursor 0: a client that stood in another run is told", async () => {
    const { client, calls } = serve(() => new Response(`{"result":{"type":"reset","epoch":"e2","resetReason":"POOL_EMPTY"}}\n`, { status: 200 }))
    const got: (string | undefined)[] = []
    for await (const ev of client.watchOrders({ cursor: 0, epoch: "e1", reconnect: false })) got.push(ev.resetReason)
    assert.deepEqual(got, ["POOL_EMPTY"])
    assert.equal(calls[0]?.url, "https://api.example/api/v1/held/events?epoch=e1")
  })
  it("reopens the feed from the cursor AND epoch it last saw, a reset included, and says where each stream resumed", async () => {
    const line = (r: object) => `${JSON.stringify({ result: r })}\n`
    const stop = new AbortController()
    const opens: string[] = []
    const { calls, sleeps, client } = serve((_s, n) => {
      if (n === 1) return new Response(line({ type: "heartbeat", epoch: "e1" }) + line({ type: "accepted", cursor: "1" }), { status: 200 })
      if (n === 2) return json({ error: { code: 14, message: "[UNAVAILABLE] restarting", details: [{ "@type": "type.googleapis.com/rfq.v1.ErrorDetail", reason: "UNAVAILABLE" }] } }, 503)
      if (n === 3) return new Response(line({ type: "heartbeat", cursor: "1", epoch: "e1" }) + line({ type: "reset", epoch: "e2", resetReason: HELD_RESET_POOL_EMPTY }), { status: 200 })
      return new Response(line({ type: "heartbeat", epoch: "e2" }) + line({ type: "accepted", cursor: "1", epoch: "e2" }), { status: 200 })
    })
    const got: string[] = []
    for await (const ev of client.watchOrders({ book: 7, signal: stop.signal, onOpen: (i) => opens.push(`${i.cursor}:${i.epoch ?? "-"}:${i.resumed}`) })) {
      got.push(`${ev.type}:${ev.cursor ?? ""}:${ev.epoch ?? ""}`)
      if (ev.epoch === "e2" && ev.type === "accepted") stop.abort()
    }
    assert.deepEqual(got, ["heartbeat::e1", "accepted:1:", "heartbeat:1:e1", "reset::e2", "heartbeat::e2", "accepted:1:e2"])
    assert.deepEqual(
      calls.map((c) => c.url.replace("https://api.example/api/v1/held/events", "")),
      ["?book=7", "?cursor=1&epoch=e1&book=7", "?cursor=1&epoch=e1&book=7", "?epoch=e2&book=7"],
    )
    // The first stream had nothing to stand on; the others resumed. A reset moved the position to its run's start.
    assert.deepEqual(opens, ["0:-:false", "1:e1:true", "0:e2:true"])
    assert.equal(sleeps.length, 3, "a wait before each reopen")
  })

  it("never repeats a call the edge refused the key of, on a route or on the feed: a bad key costs the address", async () => {
    const denied = () => json({ code: "UNAUTHENTICATED", message: "authentication required" }, 401)
    const route = serve(() => denied())
    await assert.rejects(route.client.getBookRules(1), (e: unknown) => e instanceof RfqApiError && e.status === 401)
    assert.equal(route.calls.length, 1)
    const feed = serve(() => denied())
    await assert.rejects(feed.client.watchOrders().next(), (e: unknown) => e instanceof RfqApiError && e.status === 401)
    assert.equal(feed.calls.length, 1)
    // The key is asked for on every call: a rotated key needs no restart.
    const ok = serve(() => json({}))
    await ok.client.getBookRules(1)
    await ok.client.getOrder("0x874c1039678708dfbffdc548dc9ad276")
    assert.equal(ok.keys(), 2)
  })

  it("repeats every call after the edge was unreachable, a withdraw longest; a repeated update that was applied says so", async () => {
    const down = () => json({ code: "UNAVAILABLE", message: "down" }, 503)
    // The reads: up to maxAttempts (4).
    const reads = serve(() => down())
    await assert.rejects(reads.client.listOrders(), (e: unknown) => e instanceof RfqApiError && e.status === 503)
    assert.equal(reads.calls.length, 4)
    // A withdraw: up to withdrawAttempts (8), even with retries turned off for the rest.
    const pulls = serve(() => down(), { maxAttempts: 1 })
    await assert.rejects(pulls.client.withdrawAll(), (e: unknown) => e instanceof RfqApiError && e.status === 503)
    assert.equal(pulls.calls.length, 8)
    await assert.rejects(pulls.client.getBookRules(1))
    assert.equal(pulls.calls.length, 9, "maxAttempts 1: one attempt")
    // A book update whose first answer was lost: the repeat finds its seq applied.
    const order = sourceB[0]!.heldOrder
    const lost = serve((_s, n) => (n === 1 ? down() : json({ applied: false, code: "STALE_SEQ", book: 4242, seq: "12" })))
    const up = await lost.client.replaceBookOrders(4242, { seq: 12, orders: [order] })
    assert.equal(up.attempts, 2)
    assert.equal(up.appliedEarlier, true)
    assert.deepEqual(lost.calls[1]?.body, lost.calls[0]?.body, "the same update, the same seq")
    // A stale seq at the first attempt is not one of ours.
    const stale = serve(() => json({ applied: false, code: "STALE_SEQ", book: 4242, seq: "12" }))
    const no = await stale.client.replaceBookOrders(4242, { seq: 12, orders: [order] })
    assert.equal(no.attempts, 1)
    assert.equal(no.appliedEarlier, false)
    // A client error is never repeated.
    const bad = serve(() => json({ code: "INVALID_ARGUMENT", message: "no" }, 400))
    await assert.rejects(bad.client.replaceBookOrders(4242, { seq: 13, orders: [order] }))
    assert.equal(bad.calls.length, 1)
  })

  it("the old names are the new client", () => {
    assert.equal(createHeldClient, createMakerClient)
  })
})
